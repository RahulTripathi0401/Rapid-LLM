"""Write every number shown in the presentation, slide by slide, from the result CSVs.

    python course_p3/summarize.py   -> course_p3/results/presentation_numbers.md
"""

import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
OUT = os.path.join(RES, "presentation_numbers.md")
A100, H100 = "a100_80GB_1gpu", "H100_SXM5_80GB"


def load(name):
    return pd.read_csv(os.path.join(RES, name))


def cfg(df):
    return df.apply(lambda r: "AR" if r.schedule == "AR" else f"b={int(r.b)}, R={int(r.R)}", axis=1)


def with_speedup(df, keys):
    ar = df[df.schedule == "AR"].set_index(keys).decode_s
    x = df[df.schedule != "AR"].copy()
    x["speedup"] = [ar[tuple(r[k] for k in keys)] / r.decode_s for _, r in x.iterrows()]
    return x


def md_table(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def main():
    out = ["# Numbers shown in the presentation",
           "",
           "Generated by `python course_p3/summarize.py` from the CSVs in `course_p3/results/`.",
           "Slide numbers follow the deck (12 slides). Simulated: Llama-3.1-8B, one GPU, RAPID-LLM analytical backend.",
           ""]

    req = load("required.csv")
    req["schedule_name"] = cfg(req)
    req.loc[req.kv_save.astype(str) == "True", "schedule_name"] += " + K/V call"
    cross = load("crossover.csv")
    cross = cross[cross.fits.astype(str) == "True"]

    # slide 3
    a = cross[(cross.hw == A100) & (cross.S == 512) & (cross.B == 1)]
    ar_call = a[a.schedule == "AR"].ms_per_call.iloc[0]
    d_call = a[(a.b == 8) & (a.R == 4)].ms_per_call.iloc[0]
    out += ["## Slide 3: a decode call is limited by memory",
            "Source: `results/crossover.csv` (A100, prompt 512, batch 1).",
            f"- AR call (1 position): **{ar_call:.2f} ms**",
            f"- Diffusion call (8 positions, b = 8): **{d_call:.2f} ms** (+{(d_call / ar_call - 1) * 100:.2f}%)",
            "- 16 GB = Llama-3.1-8B parameters (about 8.0 B) × 2 bytes (BF16).", ""]

    # slide 6
    rows = []
    for (B, out_len), g in req.groupby(["B", "O"]):
        ar = g[g.schedule == "AR"].iloc[0]
        for _, r in g[g.schedule != "AR"].iterrows():
            rows.append({"batch": B, "output": out_len, "schedule": r.schedule_name,
                         "AR total (s)": round(ar.total_s, 3), "diffusion total (s)": round(r.total_s, 3),
                         "speedup": f"{ar.total_s / r.total_s:.2f}×",
                         "calls": f"{int(ar.model_calls)} → {int(r.model_calls)}",
                         "TTFT AR / diff (s)": f"{ar.ttft_s:.3f} / {r.ttft_s:.3f}",
                         "peak GiB AR / diff": f"{ar.peak_gib:.2f} / {r.peak_gib:.2f}",
                         "decode TFLOP AR / diff": f"{ar.decode_tflop:.1f} / {r.decode_tflop:.1f}"})
    out += ["## Slide 6: required evaluation", "Source: `results/required.csv`.", "", md_table(pd.DataFrame(rows)), ""]

    # slide 7
    a = cross[(cross.hw == A100) & (cross.S == 512)].copy()
    a["cfg"] = cfg(a)
    shown = a[a.cfg.isin(["AR", "b=8, R=4"])]
    p = shown.pivot_table(index="B", columns="cfg", values="ms_per_call").round(2).reset_index()
    out += ["## Slide 7: cost of one call vs batch (figure `figures/slides/call_time.png`)",
            "Source: `results/crossover.csv` (A100, prompt 512). Milliseconds per model call:", "", md_table(p), ""]

    # slide 8
    sw = with_speedup(load("sweep.csv"), ["S", "B"])
    sw["cfg"] = cfg(sw)
    bmax = sw.groupby("S").B.max()
    top = sw[sw.apply(lambda r: r.B == bmax[r.S], axis=1)]
    p = top.pivot_table(index="cfg", columns="S", values="speedup").round(2).reset_index()
    p.columns = ["setting"] + [f"prompt {int(c)} (batch {int(bmax[c])})" for c in p.columns[1:]]
    out += ["## Slide 8: prompt length (figure `figures/slides/sweep.png`)",
            "Source: `results/sweep.csv`. Decode speedup over AR at the largest batch that fits in 80 GiB:", "",
            md_table(p), ""]

    # slide 9 and 10
    x = with_speedup(cross, ["hw", "S", "B"])
    x["cfg"] = cfg(x)
    rows = []
    for (hw, c), g in x[x.S == 512].groupby(["hw", "cfg"]):
        g = g.sort_values("B")
        lose = g[g.speedup < 1]
        rows.append({"GPU": "A100" if hw == A100 else "H100", "setting": c,
                     "first batch where AR wins": int(lose.B.iloc[0]) if len(lose) else f"none ≤ {int(g.B.max())}"})
    out += ["## Slide 9: A100 vs H100 (figure `figures/slides/crossover.png`)",
            "Source: `results/crossover.csv`, prompt 512, output 128. "
            "b = 32 is affected by the tiler cliff (slide 11).", "",
            md_table(pd.DataFrame(rows)), ""]
    v = x[(x.S == 512) & (x.B == 64)].pivot_table(index="cfg", columns="hw", values="speedup").round(2).reset_index()
    v.columns = ["setting"] + ["A100" if c == A100 else "H100" for c in v.columns[1:]]
    out += ["## Slide 10: validation (speedup at batch 64, prompt 512)",
            "Source: `results/crossover.csv`. Compared with Fast-dLLM v2 (arXiv 2509.26328): "
            "up to 1.5× (A100), 1.8× (H100).", "",
            md_table(v), ""]

    # slide 11
    t = load("tiler_probe.csv")
    hs = load("head_sensitivity_summary.csv")
    out += ["## Slide 11: limits",
            "Tiler cliff, source `results/tiler_probe.csv` (batch 64 × 8 KV heads, context 8192):", "",
            md_table(t), "",
            "Output-head sensitivity, source `results/head_sensitivity_summary.csv` (decode speedup vs AR):", "",
            md_table(hs), ""]

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
